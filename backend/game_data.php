/** One race by space (1-based), or null. */
function vg_election_at($space) {
  foreach (vg_elections() as $e) {
    if ((int) $e['space'] === (int) $space) return $e;
  }
  return null;
}

/** One card by key, or null. */
function vg_card($key) {
  $cards = vg_cards();
  return isset($cards[$key]) ? $cards[$key] : null;
}

/**
 * Card keys released by a campaign: dated after $afterYear (exclusive; null
 * for the opening deck) and no later than $throughYear.
 */
function vg_cards_released($afterYear, $throughYear) {
  $out = [];
  foreach (vg_cards() as $key => $card) {
    $y = (int) $card['year'];
    if ($afterYear !== null && $y <= (int) $afterYear) continue;
    if ($y > (int) $throughYear) continue;
    $out[] = $key;
  }
  return $out;
}
