/**
 * game_data.php — the board and the deck. CONTENT, not rules: the engine
 * reads this and never writes it, and tools/simulate.py parses it, so the
 * tuning always runs against exactly what the server plays.
 *
 * ONE TRACK, Nation (+, federal power) against States (-, states' rights),
 * from -5 to +5.
 *
 * THREE WAYS TO PLAY A CARD, so three numbers on it:
 *
 *   profit     money, the ONLY way to score. Play it for profit and nothing
 *              else happens.
 *   positive   favourable coverage: pushes the track this far (signed), and
 *              counts that much influence on the candidate you name.
 *   negative   hostile coverage: pushes the other way (signed) and HARDER
 *              than the card's favourable coverage, counts as influence the
 *              same way, and costs the Union `stability`. Hostile coverage
 *              is the strong, dangerous way to push: its price is disunion.
 *
 * `stability` is paid ONLY when a card is played negatively; each card
 * touches stability once at most. Profit cards have profit alone.
 *
 * BALANCE RULE: within every release batch the Nation push on offer equals
 * the States push on offer, counting both the positive and the negative
 * option of every card. tools/simulate.py asserts it; change a number here
 * and the batch must still balance, and on every card that has both the
 * hostile push must be the larger (tools/simulate.py asserts both).
 *
 * DATED RELEASE. A card enters the deck at the first campaign held in or
 * after its year. The opening deck is everything up to 1796.
 *
 * Every number is a first draft worth arguing with.
 *
 * NOTE ON QUOTING: apostrophes inside these single-quoted strings must be
 * escaped (\'). An unescaped one is a parse error that takes the site down.
 */

